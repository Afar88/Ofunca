// Generates src/pdf/pdfHtml.generated.ts: a self-contained HTML page with pdf.js
// (and its worker, run on the main thread) inlined, so PDF text extraction works
// fully offline inside a hidden WebView. No network requests are ever made.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'node_modules', 'pdfjs-dist', 'legacy', 'build');
const esc = (s) => s.replace(/<\/script/gi, '<\\/script');
const lib = esc(fs.readFileSync(path.join(dir, 'pdf.min.js'), 'utf8'));
const worker = esc(fs.readFileSync(path.join(dir, 'pdf.worker.min.js'), 'utf8'));

const bridge = `
(function () {
  function send(obj) { window.ReactNativeWebView.postMessage(JSON.stringify(obj)); }
  function b64ToBytes(b64) {
    var bin = atob(b64); var len = bin.length; var out = new Uint8Array(len);
    for (var i = 0; i < len; i++) out[i] = bin.charCodeAt(i);
    return out;
  }
  async function extract(id, b64) {
    try {
      var lib = window.pdfjsLib;
      // Worker code is already loaded in this page (globalThis.pdfjsWorker),
      // so pdf.js runs it in-process: no external worker file, no network.
      var doc = await lib.getDocument({ data: b64ToBytes(b64), isEvalSupported: false, useSystemFonts: true }).promise;
      var pages = [];
      for (var p = 1; p <= doc.numPages; p++) {
        var page = await doc.getPage(p);
        var tc = await page.getTextContent();
        var text = '';
        var lastY = null;
        for (var k = 0; k < tc.items.length; k++) {
          var it = tc.items[k];
          if (!('str' in it)) continue;
          var y = it.transform ? it.transform[5] : null;
          if (lastY !== null && y !== null && Math.abs(y - lastY) > 2) text += '\\n';
          else if (text && !/\\s$/.test(text)) text += ' ';
          text += it.str;
          if (it.hasEOL) text += '\\n';
          lastY = y;
        }
        pages.push(text);
        send({ id: id, type: 'progress', page: p, total: doc.numPages });
      }
      send({ id: id, type: 'done', pages: pages });
    } catch (e) {
      send({ id: id, type: 'error', message: String(e && e.message || e) });
    }
  }
  function onMsg(ev) {
    try { var m = JSON.parse(ev.data); if (m && m.cmd === 'extract') extract(m.id, m.data); } catch (e) {}
  }
  window.addEventListener('message', onMsg);
  document.addEventListener('message', onMsg);
  window.__extractPdf = extract;
  send({ type: 'ready' });
})();`;

const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; worker-src blob:; connect-src blob: data:"></head><body>
<script>${worker}</script>
<script>${lib}</script>
<script>${bridge}</script>
</body></html>`;

const out = path.join(root, 'src', 'pdf', 'pdfHtml.generated.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '// AUTO-GENERATED by scripts/build-pdf-html.js — do not edit.\n/* eslint-disable */\nexport const PDF_HTML: string = ' + JSON.stringify(html) + ';\n');
console.log('wrote', out, (html.length / 1e6).toFixed(2) + ' MB');
